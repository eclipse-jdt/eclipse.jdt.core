package org.eclipse.jdt.compiler.apt.tests.processors.elements;

import java.io.IOException;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.Map;
import java.util.Set;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.element.Element;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.TypeElement;

@SupportedAnnotationTypes("*")
public class ValueTypeElementProcessor extends BaseElementProcessor {
	@Override
	public synchronized void init(ProcessingEnvironment processingEnv) {
		super.init(processingEnv);
	}
	// Always return false from this processor, because it supports "*".
	// The return value does not signify success or failure!
	@Override
	public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
		if (roundEnv.processingOver()) {
			return false;
		}

		this.roundEnv = roundEnv;
		Map<String, String> options = processingEnv.getOptions();
		if (!options.containsKey(this.getClass().getName())) {
			// Disable this processor unless we are intentionally performing the test.
			return false;
		} else {
			try {
				if (options.containsKey("binary")) {
					this.isBinaryMode = true;
					this.mode = "binary";
				} else {
					this.mode = "source";
				}
				if (!invokeTestMethods(options)) {
					testAll();
				}
				if (this.reportSuccessAlready) {
					super.reportSuccess();
				}
			} catch (AssertionFailedError e) {
				super.reportError(e);
			} catch (Throwable e) {
				e.printStackTrace();
			}
		}
		return false;
	}
	protected boolean invokeTestMethods(Map<String, String> options) throws Throwable {
		Method testMethod = null;
		Set<String> keys = options.keySet();
		boolean testsFound = false;
		for (String option : keys) {
			if (option.startsWith("test")) {
				try {
					testMethod = this.getClass().getDeclaredMethod(option, new Class[0]);
					if (testMethod != null) {
						testsFound = true;
						testMethod.invoke(this,  new Object[0]);
					}
				} catch (InvocationTargetException e) {
					throw e.getCause();
				} catch (Exception e) {
					super.reportError(getExceptionStackTrace(e));
				}
			}
		}
		return testsFound;
	}

	public void testAll() throws AssertionFailedError, IOException {
		testValueType();
	}
	public void testValueType() {
		Set<? extends Element> elements = roundEnv.getRootElements();
		TypeElement vType = find(elements, "ValueType");
		assertNotNull("Value type not found", vType);
		Set<Modifier> modifiers = vType.getModifiers();
		boolean present = modifiers.contains(Modifier.VALUE);
		assertTrue("Value modifier not found", present);
		present = modifiers.contains(Modifier.PUBLIC);
		assertTrue("Value modifier not found", present);
		present = modifiers.contains(Modifier.FINAL);
		assertTrue("Value modifier not found", present);
	}
	private TypeElement find(Set<? extends Element> elements, String name) {
		for (Element element : elements) {
			if (name.equals(element.getSimpleName().toString())) {
				return (TypeElement) element;
			}
		}
		return null;
	}
}
